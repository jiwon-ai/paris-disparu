#!/usr/bin/env python3
"""Package the browser version of PARIS DISPARU.

    python3 web/build.py [ROM]        (default ROM: build/paris-disparu.gbc)

Writes build/web/ (open index.html, or serve it) and
build/paris-disparu-web.zip (index.html at the zip root, as itch.io wants).
The ROM and the emulator's wasm are embedded as base64 in game-data.js so the
page needs no server and no network.
"""
import base64
import pathlib
import shutil
import sys
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
OUT = ROOT / "build" / "web"
ZIP = ROOT / "build" / "paris-disparu-web.zip"
COPY = ["index.html", "player.js", "vendor/binjgb/binjgb.js", "vendor/binjgb/LICENSE"]


def main() -> None:
    rom = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "build" / "paris-disparu.gbc"
    rom_bytes = rom.read_bytes()
    if len(rom_bytes) < 0x150 or rom_bytes[0x143] not in (0x80, 0xC0):
        sys.exit(f"{rom}: not a Game Boy Color ROM")
    wasm = (WEB / "vendor/binjgb/binjgb.wasm").read_bytes()

    if OUT.exists():
        shutil.rmtree(OUT)
    for name in COPY:
        dst = OUT / name
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(WEB / name, dst)
    (OUT / "game-data.js").write_text(
        "// Generated by web/build.py. (c) Jiwon: the ROM is not open source.\n"
        f'window.GAME_ROM_B64="{base64.b64encode(rom_bytes).decode()}";\n'
        f'window.BINJGB_WASM_B64="{base64.b64encode(wasm).decode()}";\n')

    ZIP.unlink(missing_ok=True)
    with zipfile.ZipFile(ZIP, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(OUT.rglob("*")):
            if f.is_file():
                z.write(f, f.relative_to(OUT).as_posix())
    print(f"{OUT}/index.html\n{ZIP} ({ZIP.stat().st_size // 1024} KiB)")


if __name__ == "__main__":
    main()
