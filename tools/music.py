def stream(pairs):
    b = []
    for n, d in pairs:
        assert 1 <= d <= 255
        b += [n, d]
    return b + [0xFF]


def main():
    c = ['/* Generated by tools/music.py - do not edit by hand. Original music. */',
         '#pragma bank 4   /* MUSIC_BANK */',
         '#include "music.h"', '']
    table = []
    h = ['/* Generated by tools/music.py - do not edit by hand. */',
         '#ifndef MUSIC_SONGS_H', '#define MUSIC_SONGS_H', '']
    for i, (name, tempo, style, chords, mel) in enumerate(SONGS):
        bar = 6 if style == "waltz" else 4
        ch = chords.split()
        m, bars = melody(mel.replace("|", " "), bar)
        assert bars == len(ch), (name, bars, len(ch))
        a = accomp(ch, style)
        for tag, data in (("mel", stream(m)), ("acc", stream(a))):
            c.append("static const uint8_t %s_%s[] = {%s};" % (name.lower(), tag, ",".join(str(x) for x in data)))
        table.append("    { %d, %s_mel, %s_acc }," % (tempo, name.lower(), name.lower()))
        h.append("#define SONG_%s %d" % (name, i + 1))
    c.append("")
    c.append("const song_t music_songs[%d] = {" % len(SONGS))
    c += table
    c.append("};")
    # Pulse register value x for each note: f = 131072 / (2048 - x).
    freqs = []
    for i in range(1, 73):
        hz = 440.0 * 2 ** ((i - 1 + 24 - 57) / 12.0)     # index 1 = C2
        freqs.append(max(0, min(2047, round(2048 - 131072 / hz))))
    c.append("const uint16_t music_freq[72] = {%s};" % ",".join(str(x) for x in freqs))
    h += ["#define SONG_COUNT %d" % len(SONGS), "", "#endif", ""]
    open(os.path.join(ROOT, "src", "music_data.c"), "w").write("\n".join(c) + "\n")
    open(os.path.join(ROOT, "include", "music_songs.h"), "w").write("\n".join(h))
    print("music: %d songs" % len(SONGS))


if __name__ == "__main__":
    sys.exit(main())
