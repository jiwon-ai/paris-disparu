#!/usr/bin/env python3
"""Original music for PARIS DISPARU (composed for this game, 2026-11-24).

Writes src/music_data.c (ROM bank MUSIC_BANK) and include/music_songs.h.

Each song is a melody (wave channel 3) over an accompaniment (pulse
channel 1) generated from a chord list:
  waltz (3/4, 6 eighths a bar): bass, chord, chord  - the musette "oom-pah-pah"
  polka (2/4, 4 eighths a bar): bass, chord, fifth, chord
Melody tokens: NOTE:EIGHTHS, e.g. "A5:2", "C#6:1", "r:2" (rest).

Stream format (per channel): pairs (note, length in steps); note 0 = rest,
1..72 = C2..B7 (index into music_freq); 0xFF = loop to the start.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAMES = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}


def note(tok):
    """'C#5' -> index 1..72 (C2 = 1)."""
    n = NAMES[tok[0]]
    rest = tok[1:]
    while rest and rest[0] in "#b":
        n += 1 if rest[0] == "#" else -1
        rest = rest[1:]
    octave = int(rest)
    idx = (octave - 2) * 12 + n + 1
    assert 1 <= idx <= 72, tok
    return idx


CHORDS = {   # root, third, fifth (pitch classes as note names, octave added below)
    "C": ("C", "E", "G"), "Dm": ("D", "F", "A"), "D": ("D", "F#", "A"),
    "E7": ("E", "G#", "D"), "Em": ("E", "G", "B"), "F": ("F", "A", "C"),
    "G": ("G", "B", "D"), "Am": ("A", "C", "E"), "A": ("A", "C#", "E"),
    "Bb": ("Bb", "D", "F"), "Gm": ("G", "Bb", "D"), "C7": ("C", "E", "Bb"),
    "B": ("B", "D#", "F#"),
}


def accomp(chords, style, bass_oct=3):
    out = []
    for c in chords:
        r, t, f = CHORDS[c]
        lo = note(r + str(bass_oct))
        mid_t = note(t + str(bass_oct + 1))
        mid_f = note(f + str(bass_oct + 1))
        if style == "waltz":
            out += [(lo, 2), (mid_t, 2), (mid_f, 2)]
        else:
            lo_f = note(f + str(bass_oct))
            out += [(lo, 1), (mid_t, 1), (lo_f, 1), (mid_f, 1)]
    return out


def melody(text, bar):
    out, total = [], 0
    for tok in text.split():
        n, d = tok.split(":")
        d = int(d)
        out.append((0 if n == "r" else note(n), d))
        total += d
    assert total % bar == 0, (text[:30], total, bar)
    return out, total // bar


# name, frames per eighth, style, chords, melody (bars separated by |)
