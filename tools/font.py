# Typographic apostrophe and non-breaking space are normalised to ASCII.
ALIASES = {"’": "'", " ": " ", " ": " "}


def glyph_rows(ch):
    rows = GLYPHS[ch]
    out = []
    for r in range(8):
        src = rows[r] if r < len(rows) else "....."
        src = (src + ".....")[:5]
        out.append("." + src + "..")
    return out
